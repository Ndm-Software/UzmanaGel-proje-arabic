export default function LegalPolicyContent({ type = "terms", onTypeChange }) {
  const [activeType, setActiveType] = useState(type);

  useEffect(() => {
    setActiveType(type);
  }, [type]);

  const handleTabClick = (newType) => {
    setActiveType(newType);
    if (onTypeChange) {
      onTypeChange(newType);
    }
  };

  const policy = activeType === "privacy" ? privacyPolicy : termsPolicy;

  return (
    <article className="legal-policy" dir="rtl" lang="ar">
      <div className="legal-policy-tabs">
        <button
          type="button"
          className={`legal-policy-tab ${activeType === "terms" ? "active" : ""}`}
          onClick={() => handleTabClick("terms")}
        >
          الشروط والأحكام
        </button>
        <button
          type="button"
          className={`legal-policy-tab ${activeType === "privacy" ? "active" : ""}`}
          onClick={() => handleTabClick("privacy")}
        >
          سياسة الخصوصية
        </button>
      </div>

      <div className="legal-policy-meta" aria-label="معلومات الوثيقة">
        <span>الإصدار {POLICY_VERSION}</span>
        <span>آخر تحديث: {POLICY_UPDATED_AT}</span>
      </div>

      <p className="legal-policy-lead">{policy.lead}</p>

      <div className="legal-policy-sections">
        {policy.sections.map((section, index) => (
          <section className="legal-policy-section" key={section.title}>
            <h4>
              <span className="legal-policy-section-number" aria-hidden="true">
                {index + 1}
              </span>
              {section.title}
            </h4>

            {section.paragraphs?.map((paragraph) => (
              <p key={paragraph}>{paragraph}</p>
            ))}

            {section.items && (
              <ul>
                {section.items.map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ul>
            )}
          </section>
        ))}
      </div>

      <footer className="legal-policy-contact">
        <strong>التواصل بخصوص {policy.label}</strong>
        <p>
          يمكن إرسال الاستفسارات والطلبات إلى{" "}
          <a href={`mailto:${CONTACT_EMAIL}`}>{CONTACT_EMAIL}</a>
        </p>
      </footer>
    </article>
  );
}
